#!/usr/bin/env python3
"""Render the shared Claude cast/layout using Codex's own session metrics."""
import argparse
import json
import os
from pathlib import Path
import sys
import time
import zlib

import codex_hud_status as counters
import copilot_hud_status
import portable_images as graphics
import statusline as theme
import theme_sessions
from sixel_frames import render_frame

BASE = Path(__file__).resolve().parent


def avatar_id(instance, key=None):
    """One persistent graphics slot per HUD, including after renderer restarts."""
    return (zlib.crc32(f'agent-theme:{instance}'.encode()) & 0x3fffffff) | 0x40000000


def delete_avatar(image_id, layers):
    # Stop terminal-driven animation before dropping its placement and data.
    # Send both forms for terminals with incomplete uppercase-delete support.
    return graphics.wrap((f'\x1b_Ga=a,i={image_id},s=1,q=2\x1b\\'
                          f'\x1b_Ga=d,d=i,i={image_id},q=2\x1b\\'
                          f'\x1b_Ga=d,d=I,i={image_id},q=2\x1b\\').encode(), layers)


def legacy_avatar_ids(instance, placeholders=False):
    """Only IDs generated by earlier versions of this theme, never a global erase."""
    keys = [*theme.ANIMATIONS, *(f'{name}/{state}' for name, spec in theme.load_cast().items()
                                for state in spec.get('states', {}))]
    ids = {zlib.crc32(f'codex:{instance}:{key}'.encode()) | 0x80000000 for key in keys}
    if placeholders:
        # The old Rex renderer used these fixed IDs before HUD-scoped IDs.
        # Claude uses text portraits in Rex, so these are abandoned HUD uploads.
        ids.update(theme.kitty_id(key) for key in keys)
    return ids


class KittyAvatar:
    def __init__(self, instance, terminal='kitty', slot=None):
        self.image_id = avatar_id(slot or instance)
        self.legacy_ids = legacy_avatar_ids(instance, placeholders=terminal == 'rex')
        if slot and slot != instance: self.legacy_ids.add(avatar_id(instance))
        self.started = False
        self.cleaned = False
        self.layers = 1

    def prepare(self, layers):
        out = b''
        if not self.cleaned:
            for image_id in sorted(self.legacy_ids): out += delete_avatar(image_id, layers)
            self.cleaned = True
        return out

    def draw(self, key, row, column, layers):
        out = self.prepare(layers)
        if self.started and layers != self.layers:
            out += delete_avatar(self.image_id, self.layers)
        # Required even at startup: a killed renderer cannot run its finalizer.
        out += delete_avatar(self.image_id, layers)
        payload = theme.kitty_payload(self.image_id, *theme.animation(key), False)
        payload = payload.replace(b'a=p,U=1,', b'a=p,C=1,')
        out += graphics.position(payload, row, column, layers)
        self.started, self.layers = True, layers
        return out

    def hide(self, layers):
        needed = not self.cleaned or self.started
        out = self.prepare(layers)
        if needed:
            out += delete_avatar(self.image_id, self.layers if self.started else layers)
            self.started = False
        return out

    def close(self):
        return delete_avatar(self.image_id, self.layers) if self.started else b''


def snapshot(state, cwd, identity, now, agent='codex'):
    rates = {}
    if state.get('limits'):
        _, limits = state['limits']
        for value in (limits.get('primary'), limits.get('secondary')):
            if not isinstance(value, dict):
                continue
            key = {300: 'five_hour', 10080: 'seven_day'}.get(value.get('window_minutes'))
            if key and (value.get('resets_at') or now+1) > now:
                rates[key] = {'used_percentage': value.get('used_percent'),
                              'resets_at': value.get('resets_at')}
    wanted = 'think' if state['busy'] else ('done' if now-state.get('ended', 0) < 60 else 'idle')
    if state['busy'] and max([v['used_percentage'] or 0 for v in rates.values()] or [0]) >= 80:
        wanted = 'power'
    result = {'session_id': agent+':'+identity, 'cwd': cwd,
            'model': {'display_name': state['model']}, 'effort_level': state['effort'],
            'context_window': {'context_window_size': state.get('context_window'),
                               'used_percentage': state['context_used']},
            'permission_mode': state.get('approval', 'on-request'), 'rate_limits': rates,
            '_agent': agent, '_context_unknown': not state.get('context_window'),
            '_activity_state': state.get('activity') or ('WORKING' if state['busy'] else 'IDLE'),
            '_cast_state': state.get('cast_state', wanted) if state['busy'] else wanted,
            '_display_label': 'WORKING' if state['busy'] else '',
            '_tokens_per_second': state['speed'], '_text_panel_only': True,
            '_speed_label': state.get('speed_label', 'AVG'),
            '_total_tokens': state.get('total_tokens'),
            'prompt_cache': {'hit_ratio': state.get('cache_ratio')}, '_image_protocol': ''}
    if state.get('tier_known'): result['service_tier'] = state.get('service_tier')
    if 'fast_mode' in state: result['fast_mode'] = state['fast_mode']
    return result


def origin(args):
    def status_rows(socket=None):
        if graphics.tmux('show-options', '-gv', 'status-position', socket=socket) != 'top':
            return 0
        setting = graphics.tmux('show-options', '-gv', 'status', socket=socket)
        return 1 if setting == 'on' else int(setting) if setting.isdigit() else 0
    parts = graphics.tmux('display-message', '-p', '-t', os.environ['TMUX_PANE'],
                          '#{pane_top} #{pane_left}').split()
    top, left = map(int, parts)
    top += status_rows()
    layers = 1
    if args.outer_socket:
        parts = graphics.tmux('display-message', '-p', '-t', args.outer_pane,
                              '#{pane_top} #{pane_left}', socket=args.outer_socket).split()
        if len(parts) == 2:
            top += int(parts[0]); left += int(parts[1])
        top += status_rows(args.outer_socket)
        layers += 1
    return top+1, left+1, layers


def graphics_visible(args):
    """Passthrough escapes bypass tmux's hidden-window rendering safeguards."""
    def visible(pane, socket=None):
        value = graphics.tmux('display-message', '-p', '-t', pane,
            '#{window_active}|#{window_zoomed_flag}|#{pane_active}|#{session_attached}', socket=socket)
        parts = value.split('|')
        return (len(parts) == 4 and parts[0] == '1' and parts[3].isdigit() and int(parts[3]) > 0
                and (parts[1] != '1' or parts[2] == '1'))
    if not visible(os.environ.get('TMUX_PANE', '')): return False
    return not args.outer_socket or visible(args.outer_pane, args.outer_socket)


def graphics_slot(args):
    """Reuse the physical footer slot when a fresh CLI/HUD replaces an old one."""
    if args.outer_socket and args.outer_pane:
        return f'tmux:{args.outer_socket}:{args.outer_pane}'
    if os.environ.get('REX_BLOCK'): return 'rex:'+os.environ['REX_BLOCK']
    tty = graphics.tmux('display-message', '-p', '#{client_tty}')
    return 'tty:'+tty if tty else args.instance


def main():
    p = argparse.ArgumentParser()
    p.add_argument('--since', type=float, required=True)
    p.add_argument('--cwd', required=True)
    p.add_argument('--session-id', default='')
    p.add_argument('--instance', required=True)
    p.add_argument('--outer-socket', default='')
    p.add_argument('--outer-pane', default='')
    p.add_argument('--native-state', default='')
    p.add_argument('--watch-socket', default='')
    p.add_argument('--owner-pid', type=int, default=0)
    p.add_argument('--agent', choices=('codex', 'copilot'), default='codex')
    args = p.parse_args()
    args.log = None
    copilot = args.agent == 'copilot'
    adapter = copilot_hud_status if copilot else counters
    owner_session = theme_sessions.owned_copilot_session if copilot else theme_sessions.owned_codex_session
    home = Path(os.environ.get('COPILOT_HOME' if copilot else 'CODEX_HOME', Path.home()/('.copilot' if copilot else '.codex')))
    if args.session_id:
        args.log = adapter.session_by_id(home, args.session_id)
    # A footer can use the full five lines of every Claude layout.
    os.environ['LINES'] = '30'
    terminal = graphics.terminal_kind()
    protocol = ('kitty' if terminal in ('ghostty','kitty','rex') else
                'iterm' if terminal in ('wezterm','iterm.app','iterm2') else
                'text' if terminal == 'windowsterminal' else '')
    # Windows SIXEL passthrough corrupted the live viewport. Keep every update
    # inside this tmux pane until a graphics path is visually verified in isolation.
    native = bool(args.native_state)
    text_only = protocol == 'text' or native
    text_column = 1 if native else 13
    previous_text = previous_image = None
    state = None
    next_state = 0
    next_origin = 0
    next_visibility = 0
    visible = False
    last_size = None
    coordinates = (1, 1, 1)
    image_cells = (10,20)
    kitty_avatar = KittyAvatar(args.instance, terminal, graphics_slot(args)) if protocol == 'kitty' else None
    session_identity = args.session_id or args.instance
    sys.stdout.buffer.write(b'\x1b[2J\x1b[H\x1b[?25l')
    try:
        while True:
            if args.watch_socket and not Path(args.watch_socket).exists():
                break
            now = time.time()
            size = os.get_terminal_size()
            if size.lines != 5:
                graphics.tmux('resize-pane', '-t', os.environ['TMUX_PANE'], '-y', '5')
            if now >= next_state:
                owned = owner_session(args.owner_pid, home)
                if args.owner_pid:
                    # Explicit resume/session IDs remain authoritative when a
                    # CLI delegates its file writer outside this process tree.
                    bound = owned or args.session_id
                    args.log = adapter.session_by_id(home, bound) if bound else None
                    state = adapter.session_counters(args.log, now, counters.config_model(home) if not copilot else None)
                elif copilot: state = adapter.session_counters(args.log, now)
                else: state = counters.current_state(args, now, home)
                session_identity = owned or args.session_id or args.instance
                next_state = now+.9
            if not text_only and (now >= next_origin or size != last_size):
                coordinates = origin(args)
                if protocol == 'sixel':
                    image_cells = graphics.cell_size(socket=args.outer_socket or None,
                        pane=args.outer_pane if args.outer_socket else os.environ['TMUX_PANE'],
                        terminal=terminal)
                next_origin = now+2
                last_size = size
            if kitty_avatar is not None and now >= next_visibility:
                visible = graphics_visible(args)
                next_visibility = now+.5
            os.environ['COLUMNS'] = str(max(60, size.columns+(12 if native else 0)))
            data = snapshot(state, args.cwd, session_identity, now, args.agent)
            data['_theme_session_aliases'] = [args.instance]
            data['_theme_observer'] = args.instance
            text = theme.render(data, now)
            rows = text.splitlines()[:5]
            out = b''
            if text != previous_text:
                for i in range(5):
                    out += f'\x1b[{i+1};{text_column}H\x1b[0K'.encode() + (theme.clip(rows[i], max(0,size.columns-text_column+1)).encode() if i<len(rows) else b'')
                previous_text = text
            key, png = theme.PORTRAIT
            if kitty_avatar is not None and not visible:
                out += kitty_avatar.hide(coordinates[2])
                previous_image = None
            elif native and key != previous_image:
                target = Path(args.native_state)
                temporary = target.with_suffix('.tmp')
                temporary.write_text(json.dumps({'key': key}))
                temporary.replace(target)
                previous_image = key
            elif png and not native:
                folder = png.parent
                # Windows gets one ANSI portrait per state. It scales with text
                # and is not cleared/redrawn for every animation or usage update.
                frame = (next(iter(sorted(folder.glob('*.png'))),png) if text_only
                         else graphics.frame_at(folder, now))
                row, col, layers = coordinates
                image_key = (key, row, col, layers, image_cells, None if protocol=='kitty' else str(frame))
                if image_key != previous_image or (out and protocol == 'iterm'):
                    if protocol == 'kitty':
                        out += kitty_avatar.draw(key, row, col, layers)
                    elif protocol == 'iterm':
                        out += graphics.position(graphics.inline_png(frame), row, col, layers)
                    elif protocol == 'sixel' and frame.with_suffix('.six').exists():
                        image = render_frame(str(frame),image_cells[0]*10,image_cells[1]*5)
                        out += graphics.position(image, row, col, layers, clear=True, sync=True)
                    else:
                        for i, line in enumerate(frame.with_suffix('.ans').read_text().splitlines()):
                            out += f'\x1b[{i+1};1H'.encode()+line.encode()
                    previous_image = image_key
            if out:
                sys.stdout.buffer.write(out+b'\x1b[?25l')
                sys.stdout.buffer.flush()
            time.sleep(1 if text_only else .2 if protocol != 'kitty' else .5)
    except (KeyboardInterrupt, BrokenPipeError):
        pass
    finally:
        if kitty_avatar is not None:
            sys.stdout.buffer.write(kitty_avatar.close())
        sys.stdout.buffer.write(b'\x1b[0m\x1b[?25h')
        sys.stdout.buffer.flush()


if __name__ == '__main__':
    main()
